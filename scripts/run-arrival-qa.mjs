import { createHash,createHmac,randomBytes } from "node:crypto";
import { mkdtempSync,writeFileSync,readFileSync,mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname,join,resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync,spawnSync } from "node:child_process";
import assert from "node:assert/strict";
import { openQaQueue } from "./arrival-qa-queue.mjs";
import { arrivalTestProduct as sku } from "../lib/arrival-fulfillment.ts";

const path=dirname(fileURLToPath(import.meta.url));
const out=process.argv[2]?resolve(process.argv[2]):mkdtempSync(join(tmpdir(),"goeast-arrival-qa-"));
mkdirSync(out,{recursive:true});
const dbPath=join(out,"queue.sqlite");
const source=JSON.parse(readFileSync(join(path,"fixtures/arrival-reports.qa.json"),"utf8"));
const hotels=["Grand Hyatt Shanghai","Park Hyatt Shanghai"], routes=["official T2 taxi","Metro Line 2"];
const sign=raw=>createHmac("sha256",secret).update(raw).digest("hex");
const secret=randomBytes(32).toString("hex");
const at="2026-11-28T12:06:00.000Z", time=Date.parse(at);
const qResults=[];
let q=openQaQueue(dbPath);
for (const [index,caseData] of source.entries()){
  const id="ar_113e4567-e89b-42d3-a456-42661417400"+index;
  const checkout="ch_QA_"+index;
  const order={ id,checkout, itineraryVersion:1, expires:"2026-11-28T13:00:00Z", deadline:"2026-11-29T00:00:00Z" };
  q.register(order,caseData.trip);
  const event={id:"evt_fixture_"+index,eventType:"checkout.completed",created_at:time,object:{id:checkout,mode:"test",status:"completed",request_id:id,product:{id:sku},order:{id:"ord_QA_"+index,type:"onetime",status:"paid",amount:1290,currency:"USD",product:sku}}};
  const raw=JSON.stringify(event);
  const not=next=>{const changed=JSON.stringify({...event,object:{...event.object,...next}});return q.settle(changed,sign(changed),secret);};
  assert.equal(q.tripForPaidOrder(id),null);
  assert.equal(q.settle(raw,"0".repeat(64),secret),"invalid");
  assert.equal(not({mode:"live"}),"ignore");
  assert.equal(not({product:{id:"prod_different"}}),"ignore");
  assert.equal(not({order:{...event.object.order,amount:1291}}),"ignore");
  assert.equal(not({id:"ch_unbound"}),"ignore");
  assert.equal(q.settle(raw,sign(raw),secret),"paid");
  assert.equal(q.settle(raw,sign(raw),secret),"duplicate");
  try { throw new Error("simulated mail outage"); } catch { assert.equal(q.listUnnotified().filter(n=>n.id===id).length,1); }
  q.close();q=openQaQueue(dbPath);
  assert.equal(q.listUnnotified().filter(n=>n.id===id).length,1);
  const notice=q.listUnnotified().find(n=>n.id===id);
  assert(!notice.subject.includes(hotels[index]));
  assert(q.recordNotice(id,"notice-fixture-"+index));
  assert(!q.recordNotice(id,"duplicate-fixture-"+index));
  const claim=q.tripForPaidOrder(id);
  assert.equal(claim.trip.hotel,hotels[index]);
  const input={...caseData,...claim};
  const filename=join(out,"goeast-arrival-qa-"+(index===0?"late-t2":"day-t1")+".pdf");
  const json=join(out,"order-"+index+".json");
  writeFileSync(json,JSON.stringify(input));
  const render=(f,outFile)=>spawnSync("python",[join(path,"render-arrival-fulfillment.py"),f,outFile],{encoding:"utf8"});
  const mismatched=join(out,"mismatch.json");
  writeFileSync(mismatched,JSON.stringify({...input,trip:{...input.trip,hotel:hotels[1-index]}}));
  assert.notEqual(render(mismatched,join(out,"must-not-exist.pdf")).status,0);
  const result=render(json,filename);
  assert.equal(result.status,0,result.stderr);
  const txt=execFileSync("pdftotext",[filename,"-"],{encoding:"utf8"});
  const meta=execFileSync("pdfinfo",[filename],{encoding:"utf8"});
  assert.match(meta,/Pages:\s+1\b/);
  assert(txt.includes(hotels[index])&&txt.includes(routes[index])&&txt.includes(caseData.addressEnglish));
  const png=readFileSync(filename.replace(/\.pdf$/, ".png"));
  assert.equal(png.subarray(1,4).toString("ascii"),"PNG");
  const digest=createHash("sha256").update(readFileSync(filename)).update(png).digest("hex");
  assert(!q.completeSimulatedDelivery(id,digest,"QA-earlies"));
  assert(!q.approve(id,{id,version:2,sha256:digest,completeEvidence:true},at));
  assert(!q.approve(id,{id,version:1,sha256:digest,completeEvidence:false},at));
  assert(q.approve(id,{id,version:1,sha256:digest,completeEvidence:true},at));
  assert(!q.completeSimulatedDelivery(id,"d".repeat(64),"QA-wrong-asset"));
  assert(q.completeSimulatedDelivery(id,digest,"QA-receipt-"+index));
  assert(!q.completeSimulatedDelivery(id,digest,"QA-second-delivery"));
  qResults.push({id,hotel:hotels[index],decision:caseData.decision,state:"simulated-delivery",pages:1});
}
q.close();
console.log(JSON.stringify({ok:true,mode:"local-signed-fixture",result:qResults},null,2));
