import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
if (!process.env.PGLITE_MODULE) throw new Error("Disposable PGlite installation required");
const { PGlite } = await import(pathToFileURL(process.env.PGLITE_MODULE));
const sql = await readFile(new URL("../supabase/decision-report-live/001.sql",import.meta.url),"utf8");
