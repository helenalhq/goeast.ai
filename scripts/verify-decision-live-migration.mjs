  await db.exec("create role anon;create role authenticated;create role authenticator;create role service_role bypassrls; create table public.other_lane(id int);");
  const dnsIndependentMigrator = process.argv.includes("--non-superuser-migrator");
  if (dnsIndependentMigrator) await db.exec("create role fixture_migrator createrole; grant create on database postgres to fixture_migrator");
  await db.exec("grant select(id) on public.other_lane to public");
  if (dnsIndependentMigrator) await auth("fixture_migrator");
  await assert.rejects(()=>db.exec(sql),/isolation/);
  await db.exec("rollback");
  await auth("postgres");
  await db.exec("revoke select(id) on public.other_lane from public");
  if (dnsIndependentMigrator) await auth("fixture_migrator");
  await db.exec(sql);
  await auth("postgres");
  if (dnsIndependentMigrator) {
    const memberships = await q(`select admin_option,inherit_option,set_option from pg_auth_members
      where member='fixture_migrator'::regrole and roleid in ('p1_live_app'::regrole,'p1_live_callback'::regrole,
        'p1_live_owner_rpc'::regrole,'p1_live_payment_rpc'::regrole)`);
    assert.deepEqual(memberships, Array.from({length:4},()=>({admin_option:true,inherit_option:false,set_option:false})));
  }
  await auth("p1_live_app");
  assert.equal(await val("isolation_ok"),true);
  assert.equal((await claim(A,id))[0].claimed,true);
  assert.equal((await claim(A,other))[0].claimed,false);
  assert.equal((await claim(B,other))[0].claimed,true);
  assert.deepEqual(await rpc("get_owned",[B,id]),[]);
  assert.deepEqual(await rpc("history",[A,null,null,50]).then(r=>r.map(x=>x.id)),[id]);
  assert.equal(await val("attach_checkout",[B,id,"ch_b","https://example.invalid/b"]),false);
  assert.equal(await val("attach_checkout",[A,id,"ch_a","https://example.invalid/a"]),true);
  assert.equal(await val("attach_checkout",[A,id,"ch_other","https://example.invalid/other"]),false);
  assert.equal(await val("acquire_generation",[A,id,lease]),false);
  await assert.rejects(()=>pay(),/permission denied/);
  await assert.rejects(()=>q("select * from goeast_p1_live.decision_orders"),/permission denied/);
  await auth("p1_live_callback");
  assert.equal(await val("isolation_ok"),true);
  await assert.rejects(()=>rpc("get_owned",[A,id]),/permission denied/);
  assert.equal(await pay("evt_mismatch","ch_b"),"reconcile");
  assert.equal(await pay(),"paid");
  assert.equal(await pay(),"duplicate");
  assert.equal(await pay("evt_mismatch"),"reconcile"); // same event ID must not change settled facts
  assert.equal(await val("enqueue_event",["evt_queue","payment","ord_unbound","tx_unbound","unlinked_payment"]),"queued");
  assert.equal(await val("enqueue_event",["evt_queue","payment","ord_unbound","tx_unbound","unlinked_payment"]),"duplicate");
  assert.equal((await rpc("get_linked_payment",["ord_a","tx_a"]))[0].gross_amount,219);
  assert.deepEqual(await rpc("get_linked_payment",["ord_a","tx_wrong"]),[]);
  await auth("p1_live_app");
  assert.equal(await val("acquire_generation",[B,id,lease]),false);
  assert.equal(await val("acquire_generation",[A,id,lease]),true);
  assert.equal(await val("acquire_generation",[A,id,lease]),false);
  assert.equal(await val("finish_generation",[A,id,lease,null]),true);
  assert.equal(await val("acquire_generation",[A,id,lease]),true);
  await auth("p1_live_callback");
  assert.equal(await val("record_full_refund",["ord_a","tx_a","evt_part","prod_live","ch_a",199]),"reconcile");
  assert.equal(await val("record_full_refund",["ord_a","tx_a","evt_full","prod_live","ch_a",219]),"refunded");
  assert.equal(await pay("evt_paid_late"),"duplicate");
  await auth("p1_live_app");
  assert.equal(await val("finish_generation",[A,id,lease,"{}"]),false);
  const refunded=(await rpc("get_owned",[A,id]))[0];
  assert.equal(refunded.status,"refunded");
  assert.equal(refunded.report,null);
